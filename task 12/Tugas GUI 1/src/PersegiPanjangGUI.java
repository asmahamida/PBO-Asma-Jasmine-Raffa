    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed
        // TODO add your handling code here:
        // Mengambil input panjang dan lebar
        String inputPanjang = txtPanjang.getText().trim();
        String inputLebar = txtLebar.getText().trim();

        // Memeriksa input kosong
        if (inputPanjang.isEmpty() || inputLebar.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Panjang dan lebar harus diisi!");
            return;
        }

        try {
            // Mengubah input menjadi angka desimal
            double panjang = Double.parseDouble(inputPanjang);
            double lebar = Double.parseDouble(inputLebar);

            // Memeriksa nilai positif
            if (panjang <= 0 || lebar <= 0) {
                JOptionPane.showMessageDialog(this,
                    "Panjang dan lebar harus lebih dari 0!");
                return;
            }

            // Menghitung luas
            double luas = panjang * lebar;

            // Menghitung keliling
            double keliling = 2 * (panjang + lebar);

            // Menghitung diagonal
            double diagonal = Math.sqrt(
                (panjang * panjang) + (lebar * lebar)
            );

            // Menampilkan luas pada TextField
            txtLuas.setText(String.format("%.2f", luas));

            // Menampilkan semua hasil perhitungan
            JOptionPane.showMessageDialog(this,
                "Hasil Perhitungan Persegi Panjang\n\n"
                + "Luas       : " + String.format("%.2f", luas) + "\n"
                + "Keliling   : " + String.format("%.2f", keliling) + "\n"
                + "Diagonal   : " + String.format("%.2f", diagonal),
                "Hasil Perhitungan",
                JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Masukkan angka yang valid!");
        }
    }//GEN-LAST:event_btnHitungActionPerformed

