    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        // TODO add your handling code here:
        // Mengambil input koordinat X dan Y
        String inputX = txtX.getText().trim();
        String inputY = txtY.getText().trim();

        // Memeriksa input kosong
        if (inputX.isEmpty() || inputY.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Koordinat X dan Y harus diisi!");
            return;
        }

        try {
            // Mengubah input menjadi angka
            double x = Double.parseDouble(inputX);
            double y = Double.parseDouble(inputY);

            // Menghitung pencerminan terhadap sumbu X
            double cerminX = x;
            double cerminY = -y;

            // Menghitung pencerminan terhadap sumbu Y
            double cerminX2 = -x;
            double cerminY2 = y;

            // Menyusun hasil
            String hasil = "";

            hasil += "Titik Awal : (" + x + ", " + y + ")\n\n";

            hasil += "Pencerminan terhadap Sumbu X:\n";
            hasil += "(" + cerminX + ", " + cerminY + ")\n\n";

            hasil += "Pencerminan terhadap Sumbu Y:\n";
            hasil += "(" + cerminX2 + ", " + cerminY2 + ")";

            // Menampilkan hasil
            txtHasil.setText(hasil);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Masukkan koordinat berupa angka yang valid!");
        }
    }//GEN-LAST:event_btnProsesActionPerformed

