    private void btnTekanSayaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTekanSayaActionPerformed
        // TODO add your handling code here:
        // Mengambil input dari text field
        String input = txtAngka.getText().trim();

        // Memeriksa apakah input kosong
        if (input.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Masukkan angka terlebih dahulu!");
            return;
        }

        try {
            // Mengubah input menjadi integer
            int angka = Integer.parseInt(input);

            if (angka <= 0 || angka > 50) {
                JOptionPane.showMessageDialog(this,
                    "Masukkan angka antara 1 sampai 50!");
                return;
            }

            String hasil = "";

            // Perulangan deret angka
            for (int i = 1; i <= angka; i++) {
                hasil += i + " ";
            }

            hasil += "\n\n";

            // Perulangan pola bintang
            for (int i = 1; i <= angka; i++) {
                for (int j = 1; j <= i; j++) {
                    hasil += "* ";
                }

                hasil += "\n";
            }

            // Menampilkan hasil
            txtHasil.setText(hasil);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Input harus berupa angka!");
    }

    }//GEN-LAST:event_btnTekanSayaActionPerformed

