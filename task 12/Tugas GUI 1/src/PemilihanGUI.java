    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        // TODO add your handling code here:
        String prodi = (String) cmbProdi.getSelectedItem();

            if (prodi == null) {
                JOptionPane.showMessageDialog(this,
                    "Pilih program studi terlebih dahulu!");
                return;
            }

            // 2. Menentukan kode program studi
            String kodeProdi = "";

            switch (prodi) {
                case "Hukum (S1)":
                    kodeProdi = "110110";
                    break;

                case "Ilmu Ekonomi (S1)":
                    kodeProdi = "120610";
                    break;

                case "Manajemen (S1)":
                    kodeProdi = "120310";
                    break;

                case "Kedokteran (S1)":
                    kodeProdi = "130110";
                    break;

                case "Kedokteran Hewan (S1)":
                    kodeProdi = "130210";
                    break;

                case "Matematika (S1)":
                    kodeProdi = "140110";
                    break;

                case "Kimia (S1)":
                    kodeProdi = "140210";
                    break;

                case "Fisika (S1)":
                    kodeProdi = "140310";
                    break;

                case "Biologi (S1)":
                    kodeProdi = "140410";
                    break;
            }

            // 3. Mengambil tahun angkatan
            String angkatan = "";

            if (rb2019.isSelected()) {
                angkatan = "19";
            } else if (rb2020.isSelected()) {
                angkatan = "20";
            } else if (rb2021.isSelected()) {
                angkatan = "21";
            } else {
                JOptionPane.showMessageDialog(this,
                    "Pilih angkatan terlebih dahulu!");
                return;
            }

            // 4. Mengambil nomor urut
            String nomorUrut = txtNomorUrut.getText().trim();

            if (nomorUrut.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                    "Nomor urut harus diisi!");
                return;
            }

            try {
                int nomor = Integer.parseInt(nomorUrut);

                if (nomor < 1 || nomor > 999) {
                    JOptionPane.showMessageDialog(this,
                        "Nomor urut harus antara 1 sampai 999!");
                    return;
                }

                // 5. Kode status mahasiswa reguler
                String status = "0";

                // 6. Mengubah nomor menjadi 3 digit
                String nomorAkhir = String.format("%03d", nomor);

                // 7. Menggabungkan seluruh kode
                String npm = kodeProdi + angkatan + status + nomorAkhir;

                // 8. Menampilkan hasil
                lblHasil.setText(npm);

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this,
                    "Nomor urut harus berupa angka!");
            }
    }//GEN-LAST:event_btnProsesActionPerformed

